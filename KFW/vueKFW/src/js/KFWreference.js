export function getBreeseScore(value, boatsToScore) {
	if (boatsToScore) {
		let boatChainLength = value
		if (boatChainLength >= 5) return 32
		if (boatChainLength >= 4) return 16
		if (boatChainLength >= 3) return 8
		if (boatChainLength >= 2) return 4
		if (boatChainLength >= 1) return 2
		return 0
	}
	// Otherwise, change the score to the boat length
	let score = value
	if (score === 32) return 5
	if (score === 16) return 4
	if (score === 8) return 3
	if (score === 4) return 2
	if (score === 2) return 1
	return 0
}
