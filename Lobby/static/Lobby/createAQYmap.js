function checkValidMap(showSpan) {
	let tileCount = [0, 0, 0, 0]
	for (let i = 0; i < boardTiles.length; i++) {
		if (boardTiles[i][0] === 0) tileCount[0]++
		if (boardTiles[i][0] === 1) tileCount[0]++
		if (boardTiles[i][0] === 10) tileCount[0]++
		if (boardTiles[i][0] === 11) tileCount[0]++

		if (boardTiles[i][0] === 2) tileCount[1]++
		if (boardTiles[i][0] === 3) tileCount[1]++
		if (boardTiles[i][0] === 12) tileCount[1]++
		if (boardTiles[i][0] === 13) tileCount[1]++

		if (boardTiles[i][0] === 4) tileCount[2]++
		if (boardTiles[i][0] === 5) tileCount[2]++
		if (boardTiles[i][0] === 14) tileCount[2]++
		if (boardTiles[i][0] === 15) tileCount[2]++

		if (boardTiles[i][0] === 6) tileCount[3]++
		if (boardTiles[i][0] === 7) tileCount[3]++
		if (boardTiles[i][0] === 16) tileCount[3]++
		if (boardTiles[i][0] === 17) tileCount[3]++
	}
	if (showSpan) document.getElementById("invalidMapCautionSpanAQY").style.display = "none"
	for (let count of tileCount) {
		if (count > 2) {
			if (showSpan) document.getElementById("invalidMapCautionSpanAQY").style.display = "block"
			return false
		}
	}
	return true
}
